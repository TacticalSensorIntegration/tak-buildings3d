def attribution_text(lines, src=None):
    """Text of the ATTRIBUTION.txt shipped in every tileset zip."""
    out = ["This 3D Tiles dataset was generated by tak-buildings3d:",
           f"  {REPO_URL}",
           "That open-source tool is the method used to derive it from the data below (ODbL 4.6).", "",
           "Credits (show these wherever the data is displayed):"]
    out += [f"  - {a}" for a in lines]
    out += ["", "Licences:",
            "  - Building data is a Produced Work of OpenStreetMap data under the Open Database Licence (ODbL 1.0):",
            "    https://www.openstreetmap.org/copyright . Credit 'OpenStreetMap contributors'.",
            "  - Copernicus DEM GLO-30: https://spacedata.copernicus.eu/collections/copernicus-digital-elevation-model"]
    if src:
        licence = src.get("licence") or "licence confirmed by the user who added it"
        out.append(f"  - Roof imagery ({src['name']}): {licence}"
                   + (f" - {src['licence_url']}" if src.get("licence_url") else ""))
    return "\n".join(out) + "\n"


@dataclass
class Params:
    name: str
    clip: object                         # shapely geometry, lon/lat
    pbf: Path | None = None              # None -> Overpass API
    roofs: str = "osm"                   # "osm" | "colour" | "texture"
    imagery: object = None               # source id or config dict; needed unless roofs="osm"
    roof_mpp: float | None = None        # texture m/px; None = imagery.default_mpp
    roof_quality: int = 80
    tile_cell: float = 150.0             # leaf tile size (m)


def circle(lat, lon, radius_m):
    """Approximate geodesic circle as a lon/lat polygon."""
    dlat = radius_m / 111320.0
    dlon = dlat / math.cos(math.radians(lat))
    ring = [(lon + dlon * math.cos(t), lat + dlat * math.sin(t))
            for t in (2 * math.pi * k / 64 for k in range(64))]
    return shape({"type": "Polygon", "coordinates": [ring + ring[:1]]})


def bbox(min_lon, min_lat, max_lon, max_lat):
    """Lon/lat rectangle as a polygon."""
    return box(min_lon, min_lat, max_lon, max_lat)


def geojson_geometry(gj):
    """Polygon/MultiPolygon from a GeoJSON geometry, Feature or FeatureCollection."""
    if isinstance(gj, (str, Path)):
        gj = json.loads(Path(gj).read_text())
    feats = gj.get("features") or [gj]
    g = make_valid(unary_union([shape(f.get("geometry", f)) for f in feats]))
    if g.geom_type == "GeometryCollection":          # e.g. a self-touching ring: keep the areas
        g = unary_union([p for p in g.geoms if p.geom_type in ("Polygon", "MultiPolygon")])
    if g.is_empty or g.geom_type not in ("Polygon", "MultiPolygon"):
        raise ValueError("the area must be a polygon")
    return g


def safe_name(name: str) -> str:
    """Name safe for a folder or file: other characters become "_", max 64."""
    s = "".join(c if c.isalnum() or c in "-_" else "_" for c in name.strip())[:64]
    if not s:
        raise ValueError("empty name")
    return s


def extract_pbf(pbf: Path, clip, work: Path) -> Path:
    """Cut the clip's bbox out of a large .pbf with osmium-tool, if installed."""
    if not shutil.which("osmium"):
        return pbf
    x0, y0, x1, y1 = clip.bounds
    out = work / "area.osm.pbf"
    from .regions import run_osmium      # imported here: regions imports this module
    run_osmium(["extract", "-b", f"{x0},{y0},{x1},{y1}", "-s", "complete_ways",
                "--overwrite", "-o", str(out), str(pbf)])
    return out


def run(p: Params, log=print, progress=None) -> dict:
    """Build out/<name>/ (tileset, zip, report.json) and return a summary dict."""
    name = safe_name(p.name)
    final = OUT / name
    out = OUT / f".{name}.building"          # build aside; replace the old build only on success
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    try:
        return _run(p, name, out, final, log, progress or (lambda f: None))
    except BaseException:
        shutil.rmtree(out, ignore_errors=True)
        raise


def _osm_source(pbf):
    """(region id, download timestamp) of the OSM data, or (None, None) if unknown."""
    if not pbf:
        return "overpass", time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    meta = Path(str(pbf)[: -len(".osm.pbf")] + ".json") if str(pbf).endswith(".osm.pbf") else None
    if meta and meta.exists():
        m = json.loads(meta.read_text())
        return m.get("id"), m.get("downloaded")
    return None, None


def _run(p, name, out, final, log, progress):
    tiles_dir = out / f"{name}_buildings"
    c = p.clip.centroid
    lat, lon = c.y, c.x

    osm_region, osm_date = _osm_source(p.pbf)
    log("[1/4] OSM buildings")
    if p.pbf:
        with tempfile.TemporaryDirectory() as tmp:
            src = extract_pbf(Path(p.pbf), p.clip, Path(tmp))
            blds = osm.from_pbf(src, p.clip)
    else:
        x0, y0, x1, y1 = p.clip.bounds
        data = osm.fetch(("bbox", y0, x0, y1, x1), DATA / "overpass")
        blds = [b for b in osm.buildings(data) if p.clip.intersects(b["geom"])]
    if not blds:
        raise ValueError("no buildings in the selected area")
    log(f"      {len(blds)} buildings/parts")

    progress(0.05)
    log("[2/4] terrain (Copernicus GLO-30)")
    bx = [b["geom"].bounds for b in blds]
    terrain = Terrain(min(b[0] for b in bx), min(b[1] for b in bx), max(b[2] for b in bx), max(b[3] for b in bx))
    anchor_msl = terrain.sample(lon, lat)
    anchor_hae = msl_to_hae(lon, lat, anchor_msl)
    frame = LocalFrame(lat, lon)
    log(f"      anchor ground {anchor_msl:.1f} m MSL = {anchor_hae:.1f} m HAE")

    roofs = p.roofs
    src = None
    tiles = None
    if roofs != "osm":
        if p.imagery is None:
            raise ValueError(f"roofs={roofs} needs an imagery source")
        if p.imagery == "auto":
            src = imagery.best_source(DATA, p.clip, roofs)
            if src is None:
                raise ValueError("no built-in imagery covers this area; add an imagery URL")
        else:
            src = p.imagery if isinstance(p.imagery, dict) else imagery.get_source(DATA, p.imagery)
        tiles = imagery.open_source(src, DATA / "tiles")
    progress(0.1)
    roof_mpp = p.roof_mpp or (imagery.default_mpp(src, lat) if src and roofs == "texture"
                               else imagery.COLOUR_MPP)
    log(f"[3/4] meshes (roofs: {roofs}{', ' + src['name'] if src else ''}"
        f"{f' @ {roof_mpp} m/px' if roofs == 'texture' else ''})")
    if tiles:
        mpp = roof_mpp if roofs == "texture" else max(roof_mpp, 0.3)   # mesh.build samples colours at >= 0.3
        tiles.prefetch_area([b["geom"].bounds for b in blds], mpp, roofs == "texture", log=log,
                            progress=lambda f: progress(0.1 + 0.6 * f))
    buildings, report = mesh.build(blds, frame, terrain, anchor_hae, msl_to_hae,
                                   roof_mode=roofs, tiles=tiles, roof_mpp=roof_mpp, log=log,
                                   imagery_fine=bool(src) and imagery.native_mpp(src, lat) <= imagery.TEXTURE_MAX_MPP)
    if tiles:
        log(f"      imagery tiles: {tiles.fetched} downloaded, {tiles.failed} failed")
        if getattr(tiles, "direct", 0) or getattr(tiles, "fallback", 0):
            log(f"      roofs cut from NAIP's own grid: {tiles.direct}, via map tiles: {tiles.fallback}")
        if tiles.failed and not tiles.fetched:
            log("      WARNING: no imagery tiles could be fetched; check the URL")
    ntri = sum(len(q.faces) for b in buildings for q in b.parts)
    log(f"      {len(buildings)} buildings, {ntri} tris")
    for k in ("roof_shape", "facade", "class"):
        log(f"      {k}: {dict(Counter(r[k] for r in report).most_common())}")
    checks = Counter((r["roof_colour_tag_check"], r["roof_colour_source"]) for r in report if "roof_colour_tag_check" in r)
    if checks:
        log("      roof:colour tags vs imagery: " + ", ".join(
            f"{n} {chk}{' (imagery used)' if used == 'imagery' else ' (tag kept)'}" for (chk, used), n in sorted(checks.items())))

    progress(0.8)
    log("[4/4] 3D Tiles")
    stats = export.write_3dtiles(buildings, tiles_dir, (lat, lon, anchor_hae), p.tile_cell, p.roof_quality)
    attribution = [ATTRIBUTION_OSM, ATTRIBUTION_DEM, ATTRIBUTION_GEOID]
    if src:
        attribution.insert(1, src["attribution"])
    (tiles_dir / "ATTRIBUTION.txt").write_text(attribution_text(attribution, src))
    zip_path = out / f"{name}_buildings.zip"
    export.zip_tileset(tiles_dir, zip_path)
    leaf = [s for _, s, lv in stats if lv == 0]
    lod = [s for _, s, lv in stats if lv > 0]
    summary = {
        "name": name, "roofs": roofs, "buildings": len(buildings), "triangles": ntri,
        "leaf_tiles": len(leaf), "leaf_bytes": sum(leaf), "lod_tiles": len(lod), "lod_bytes": sum(lod),
        "zip": zip_path.name, "zip_bytes": zip_path.stat().st_size,
    }
    meta = {
        "anchor": {"lat": lat, "lon": lon, "hae_m": round(anchor_hae, 3), "msl_m": round(anchor_msl, 3)},
        "roofs": roofs, "source": Path(p.pbf).name if p.pbf else "overpass",
        "imagery": ({k: src.get(k) for k in ("id", "name", "url", "max_zoom", "attribution")} if src else None),
        "params": {"roofs": roofs, "imagery": src.get("id") if src else None, "roof_mpp": roof_mpp,
                   "tile_cell": p.tile_cell, "region": osm_region},
        "osm": {"region": osm_region, "downloaded": osm_date},
        "roof_mpp": roof_mpp if roofs == "texture" else None,
        "area": mapping(p.clip),
        "heights": "WGS84 ellipsoidal (HAE); DEM EGM2008 converted with PROJ geoid grid",
        "attribution": attribution, "summary": summary, "buildings": report,
    }
    (out / "report.json").write_text(json.dumps(meta, indent=1))
    log(f"done -> {final}: {len(leaf)} leaf b3dm {sum(leaf) / 1024:.0f} KB "
        f"(largest {max(leaf) / 1024:.0f} KB) + {len(lod)} LOD b3dm {sum(lod) / 1024:.0f} KB")
    if final.exists():                  # last cancel check was the log above; replace the old build
        shutil.rmtree(final)
    out.rename(final)
    return summary
